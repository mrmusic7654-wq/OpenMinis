/**
 * The visual theme catalogue. A theme is an *aesthetic* — accent hue, surface
 * tints, bubble colours — layered on top of the light / dark decision, which
 * stays with the existing System / Light / Dark picker. Every theme therefore
 * ships a light AND a dark variant, so "Crystal" reads icy-white in light mode
 * and deep-teal in dark mode, and switching the OS appearance never changes
 * the theme the user chose.
 *
 * Persistence: `appearance_prefs` / [KEY_APP_THEME] as the [id] string (not an
 * index) so adding or reordering themes never silently changes a user's pick.
 * The same string tokens are exposed to the agent as `appearance.app_theme`
 * via the config registry.
