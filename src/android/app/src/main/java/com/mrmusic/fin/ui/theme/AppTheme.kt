/**
 * One light-or-dark rendition of an [AppTheme]. Only the colours that give a
 * theme its character live here; everything else in [ChatPalette] /
 * `MaterialTheme.colorScheme` is derived from these plus the neutral base
 * palette for the mode (see `Theme.kt`).
 */
data class ThemeVariant(
    val primary: Color,
    val onPrimary: Color,
    val primaryContainer: Color,
    val onPrimaryContainer: Color,
    val secondary: Color,
    val onSecondary: Color,
    val secondaryContainer: Color,
    val onSecondaryContainer: Color,
    val tertiary: Color,
    val onTertiary: Color,
    val tertiaryContainer: Color,
    val onTertiaryContainer: Color,
    /** Grouped page background (settings, lists). */
    val background: Color,
    val onBackground: Color,
    /** Grouped card surface. */
    val card: Color,
    /** Elevated card / sheet surface. */
    val cardElevated: Color,
    val onSurfaceVariant: Color,
    val outline: Color,
    /** Chat canvas behind the message list. */
    val chatBackground: Color,
    /** User message bubble fill. */
    val userBubble: Color,
    /** New-chat FAB / accent chip. */
    val fabAccent: Color,
    val link: Color,
    val thinking: Color,
    val codeBlockBg: Color,
    val codeBlockText: Color,
    val inlineCodeText: Color,
    /** Three colours the theme picker paints as a preview swatch. */
    val swatch: List<Color>,
)
